// Proyección del mapa completo: x% = (x + 6000) / 120 · y% = (5000 − y) / 100.
export const toPct = (x, y) => ({
  x: Math.round(((x + 6000) / 120) * 100) / 100,
  y: Math.round(((5000 - y) / 100) * 100) / 100,
});

